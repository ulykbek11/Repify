import { Platform } from 'react-native';
import { API_URL, DEMO_MODE } from '../config';
import samples from '../data/samples.json';
import { canExtractInBrowser, extractPosesInBrowser } from './poseExtractor';

export class ApiError extends Error {
  constructor(message, kind = 'http', status) {
    super(message);
    this.kind = kind; // 'network' | 'http'
    this.status = status;
  }
}

async function request(path, options = {}, timeoutMs = 120000) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const response = await fetch(`${API_URL}${path}`, { ...options, signal: controller.signal });
    if (!response.ok) {
      let detail = `HTTP ${response.status}`;
      try {
        const body = await response.json();
        if (body?.detail) detail = typeof body.detail === 'string' ? body.detail : JSON.stringify(body.detail);
      } catch (_) {}
      throw new ApiError(detail, 'http', response.status);
    }
    return await response.json();
  } catch (error) {
    if (error instanceof ApiError) throw error;
    throw new ApiError(error.message, 'network');
  } finally {
    clearTimeout(timer);
  }
}

export const getHealth = () => (DEMO_MODE ? Promise.resolve({ engine: 'demo' }) : request('/health', {}, 5000));

// Sample analyses are generated by the backend (backend/scripts/export_samples.py) and bundled with
// the app, so the demo works without a server. With a backend configured it is asked first.
export function bundledSample(exercise, language) {
  const entry = samples[exercise]?.[language] || samples[exercise]?.en;
  if (!entry) throw new ApiError(`No sample for ${exercise}`, 'http', 404);
  return { ...entry, demo: true };
}

export async function sampleAnalysis(exercise, language) {
  if (DEMO_MODE) return bundledSample(exercise, language);
  try {
    return await request(`/api/sample-analysis?exercise=${exercise}&language=${language}`, {}, 8000);
  } catch (error) {
    if (error instanceof ApiError && error.kind === 'network') return bundledSample(exercise, language);
    throw error;
  }
}

// Vercel Functions reject request bodies above 4.5 MB, so larger videos cannot be uploaded to a
// Vercel-hosted backend. The web build therefore extracts poses in the browser and only sends the
// landmarks; a small clip falls back to the server if the browser cannot run MediaPipe.
const SERVER_UPLOAD_LIMIT = 4 * 1024 * 1024;

// asset: result of expo-image-picker ({ uri, file? })
export async function extractPoses(asset) {
  const form = new FormData();
  if (Platform.OS === 'web') {
    const file = asset.file || (await (await fetch(asset.uri)).blob());
    let browserError = null;
    if (canExtractInBrowser) {
      try {
        const poses = await extractPosesInBrowser(file);
        if (!poses.length) throw new ApiError('No person detected in the video', 'http', 422);
        return poses;
      } catch (error) {
        if (error instanceof ApiError) throw error;
        browserError = error;
      }
    }
    if (file.size > SERVER_UPLOAD_LIMIT) {
      throw new ApiError(browserError ? `Pose detection failed in the browser: ${browserError.message}` : 'Video too large', 'http', 413);
    }
    form.append('video', file, asset.fileName || 'video.mp4');
  } else {
    form.append('video', { uri: asset.uri, name: 'video.mp4', type: 'video/mp4' });
  }
  const data = await request('/api/extract-poses', { method: 'POST', body: form }, 600000);
  return data.pose_sequence;
}

export const analyze = ({ poseSequence, exercise, language, heightCm }) =>
  request(
    '/api/analyze',
    {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        exercise,
        pose_sequence: poseSequence,
        language,
        user_height_cm: heightCm || null,
        camera_angle: 'side_profile',
      }),
    },
    600000
  );
